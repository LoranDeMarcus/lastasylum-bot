    # Учтённый остаток склянок на старте (необязательно: бот всё равно
    # прочитает реальный остаток после первого же применения).
    # 0 = «неизвестно» -> разрешаем один пробный рефилл, чтобы узнать остаток.
    flask_count_start: int = 0

    # --- Виджет «Отряд N/4» (левый верх) ---
    # Виджет смещается по вертикали между кадрами -> якорь-слово «Отряд» ищем
    # в полосе, счётчик читаем по фикс. смещению от найденного матча.
    squad_total: int = 4
    squad_header_band: tuple = (0, 200, 470, 220)   # (x, y, w, h) полоса поиска якоря
