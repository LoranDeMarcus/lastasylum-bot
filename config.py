    mob_hsv_low: tuple = (14, 120, 120)
    mob_hsv_high: tuple = (28, 255, 255)
    boss_hsv_low: tuple = (5, 120, 120)     # (не используется: боссы того же тона, делим по размеру)
    boss_hsv_high: tuple = (18, 255, 255)
