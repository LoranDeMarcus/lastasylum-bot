class Config:
    # --- ADB ---
    adb_path: str = r"C:\Program Files\BlueStacks_nxt\HD-Adb.exe"
    adb_serial: str = "emulator-5554"    # BlueStacks_nxt (проверено: adb devices)

    # --- Пороги стратегии ---
    flask_stop_threshold: int = 180      # склянок < 180 -> STOP
    energy_refill_threshold: int = 20    # энергия < 20 -> REFILL
    farm_levels: frozenset = frozenset({5})
    boss_level_threshold: int = 50       # эвристика: level >= -> кандидат в боссы
    mob_squad: int = 2
    boss_squad: int = 1
    squad_slots: dict = field(default_factory=lambda: {1: (200, 1630), 2: (425, 1630), 3: (650, 1630), 4: (875, 1630)})
    mob_energy_cost: int = 10
    boss_energy_cost: int = 20

    # --- Экран (ADB-разрешение BlueStacks, проверено screencap) ---
    screen_w: int = 1080
    screen_h: int = 1920

    # --- Регионы чтения чисел (x, y, w, h); плейсхолдеры до калибровки ---
    # Энергия на HUD карты (слева-вверху). Белые цифры лежат ПОВЕРХ зелёной
    # полосы заполнения -> читаются с отсечкой по яркости (см. read_energy):
    # Otsu склеивал полосу с цифрами и давал 9 вместо 50.
    region_energy: tuple = (58, 155, 68, 32)
    energy_white_threshold: int = 190
    region_deployed: tuple = (0, 0, 0, 0)         # TODO: индикатора «Отряд X/4» на карте нет
    region_flasks: tuple = (462, 1543, 105, 50)   # «В наличии: N» у фиолетовой склянки (окно энергии)

    # --- Координаты окна энергии/отправки (фикс., окно с фикс. вёрсткой) ---
    energy_open_xy: tuple = (962, 1802)   # «+» на экране отправки -> открыть окно энергии
    flask_use_xy: tuple = (858, 1540)     # «Использовать» у фиолетовой склянки +50
    energy_close_xy: tuple = (1000, 372)  # крестик закрытия окна энергии

    # --- HSV-маска целей (мобы «5» и боссы «70» — один жёлто-оранжевый тон) ---
    # красные черепа «28» (H≈8) в диапазон НЕ попадают -> сами отсеиваются
    mob_hsv_low: tuple = (14, 120, 120)
    mob_hsv_high: tuple = (28, 255, 255)
    boss_hsv_low: tuple = (5, 120, 120)     # (не используется: боссы того же тона, делим по размеру)
    boss_hsv_high: tuple = (18, 255, 255)
    blob_min_area: int = 1500
    blob_max_area: int = 4200     # моб ~2000, босс (рогатый) ~3100-3500
    # --- Классификация моб/босс по РОГАМ через aspect (зум-инвариантно) ---
    # Плоский череп (моб) aspect≈0.97; рогатый (босс любого ур.) aspect≈1.13.
    boss_aspect_min: float = 1.05     # aspect >= -> босс (рога делают шире-чем-выше)
    target_max_aspect: float = 1.32   # aspect больше -> не череп (повозка ~1.24 и т.п.)
    # HUD-зоны (доли W×H), где детекция игнорируется: верх (аватар/баннер/миникарта),
    # правое меню (территория/альянс), правый-нижний угол (кнопка дома)
    hud_zones: tuple = (
        (0.0, 0.0, 1.0, 0.107),
        (0.755, 0.0, 1.0, 0.271),
        (0.74, 0.885, 1.0, 1.0),
    )

    # --- Состояние отряда: верхний-левый виджет «Отряд» ---
    # Регион метки состояния (x,y,w,h); слова «Перемещение»/«Возвращение...».
    # busy = max(score) > threshold; марш/возврат = argmax; свободен = виджета нет.
    # Регион широкий: виджет «Отряд» смещается по вертикали между видами
    # (на карте vs зум-ин базы) -> ищем слово в полосе, а не в узком боксе.
    squad_state_region: tuple = (120, 320, 360, 140)
    squad_state_threshold: float = 0.6
    # --- «Поиск вора» (Особое событие): near-base мобы, короткий марш ---
    event_button_xy: tuple = (970, 430)        # «Особое событие» (правый столбец, зум-ин)
    search_thief_tab_xy: tuple = (450, 205)    # вкладка «Поиск вора»
    search_button_xy: tuple = (285, 1815)      # кнопка «Поиск»
    search_result_xy: tuple = (540, 965)       # найденный моб центрируется сюда
    # «Поиск» не даёт панель моба столько раз подряд -> стоп (событие кончилось,
    # вёрстка иная, экран не тот) — чтобы не тапать вслепую по меню
    max_search_failures: int = 3
    # Слать следующего сразу как «Возвращение» (True) или ждать полного возврата (False)
    send_next_on_return: bool = True

    # --- Фиксированные координаты кнопок (калибруются; -1 = искать шаблоном) ---
    templates_dir: str = "templates"
    template_match_threshold: float = 0.8
    jitter_px: int = 4
    stop_file: str = "STOP"
    # Стратегия фарма: True = «Поиск вора» (near-base мобы, короткий марш, весь
    # цикл в зум-ине, гейт по виджету отряда); False = старая детекция на отзуме.
    use_search_strategy: bool = True
    # dry-run: движок только логирует решения, НЕ тапает (см. engine)
    dry_run: bool = False
    # verify после тапа по цели: ждать панель «Атака»/«Штурм» столько секунд
    panel_verify_timeout_s: float = 2.5
    # Прогноз боя в превью: «Лёгкая победа»(win) / «Без шансов на победу»(lose).
    # Босса штурмуем только при win (реком. мощь босса может быть >> нашей).
    verdict_threshold: float = 0.7
    # Закрыть превью/панель без отправки: тап по затемнённой области над панелью
    preview_close_xy: tuple = (540, 300)
    # Двухтапный тап по мобу: промах зумит+центрирует цель -> второй тап по
    # центру-спрайту (зум ставит точку тапа в центр экрана; спрайт чуть ниже).
    zoom_center_tap_offset_y: int = 55
    # GUARD ВИДА: действовать только на чистой отзум-карте. Сигнатура —
    # легенда «Моя территория/Члены альянса/Глава гильдии» (top-right, есть
    # только на карте мира; на зум-ине/в меню — нет). Иначе движок ждёт
    # (сам отзумить не может — щипка нет; нужен человек), чтобы не тыкать меню.
    worldmap_legend_region: tuple = (800, 260, 280, 260)
    worldmap_threshold: float = 0.6
    # Не на карте (после отправки камера зумит за армией / промах) -> пробуем
    # авто-отзум щипком столько раз подряд; если не помогло (вероятно меню) —
    # ждём человека.
    max_pinch_recover: int = 3

    # --- Режим «Элитная скверна» (штурм боссов через диалог поиска) ---
    # strategy: "corruption" | "thief" | "map". Оставлено рядом с
    # use_search_strategy для обратной совместимости старых раннеров.
    strategy: str = "corruption"
    corruption_search_icon_xy: tuple = (78, 1530)   # лупа в левом столбце -> диалог поиска
    corruption_tab_xy: tuple = (843, 962)           # вкладка «Элитная скверна» (тап безусловный)
    corruption_search_xy: tuple = (548, 1785)       # кнопка «Поиск»
    corruption_assault_xy: tuple = (540, 1245)      # «Штурм» на панели босса (фолбэк к шаблону)
    corruption_energy_cost: int = 20                # стоимость штурма
    # Гейт «Легкая победа». Выключен: уровень скверны фиксирует человек, значит
    # босс заведомо проходим. Включать, если поднять уровень.
    corruption_verdict_gate: bool = False
    corruption_poll_interval_s: float = 10.0        # опрос, когда все отряды заняты
    # «Назад» на чистой карте открывает «Выйти из игры?» — жмём «Отмена»
    # (фолбэк к шаблону exit_cancel), иначе следующий тап подтвердит выход.
    exit_cancel_xy: tuple = (297, 1030)
    # Окно «Восстановить энергию» в этом режиме открывается кнопкой «Увеличить
    # энергию» на превью. Строк 3 или 4 (при четырёх третья — зелёная +10),
    # поэтому Y кнопки «Использовать» берём от найденной строки фиолетовой
    # склянки, а фиксирован только X.
    flask_use_x: int = 858
    energy_window_close_xy: tuple = (1000, 375)
    # «Увеличить энергию» стоит на месте «Начать Штурм» (превью при нехватке)
    corruption_boost_energy_xy: tuple = (548, 1367)
    # Счётчик «сколько склянок ещё влезет» в строке: (x, dy от центра строки,
    # w, h). ОДИН тап «Использовать» тратит РОВНО ОДНУ склянку (+50 энергии),
    # счётчик лишь показывает верхний предел — больше него тапать бессмысленно.
    flask_qty_region_rel: tuple = (520, -30, 100, 60)
    # Сколько раз подряд жать «Использовать»: 2 тапа = +100 энергии.
    flask_use_taps: int = 2
    # «В наличии: N» — виден только когда счётчик количества исчез (энергии
    # осталось долить меньше 50), то есть ПОСЛЕ применения склянок.
    flask_stock_region_rel: tuple = (465, 6, 80, 34)

    # --- Антибот: сторож незнакомого экрана ---
    watchdog_enabled: bool = True
    # 'log' — только классифицирует и сохраняет кадры (режим наблюдения),
    # 'stop' — боевой. Первую живую сессию гоняем в 'log': иначе рискуем
    # получить сторожа, который глушит бота на каждом рекламном баннере.
    watchdog_action: str = "log"
    watchdog_wait_s: float = 4.0        # пауза между раундами ожидания
    watchdog_wait_rounds: int = 3       # ~12 с без единого тапа
    watchdog_back_wait_s: float = 2.0   # пауза после спасательного BACK
    watchdog_dir: str = "reference/anomaly"
    watchdog_beep: bool = True

    # --- Антибот: якорь «мы в игре» (HUD энергии, левый верх) ---
    # Работает при ЛЮБОМ зуме, в отличие от worldmap_legend (её нет в зум-ине,
    # а после отправки камера уезжает за армией). Берём ИКОНКУ молнии, а не
    # цифры: цифры меняются (81 / 50 / 42 на разных кадрах), иконка нет.
    # Ищем в полосе с запасом: HUD слегка смещается между видами.
    hud_energy_region: tuple = (0, 120, 200, 110)
    hud_energy_threshold: float = 0.7

    # --- Возврат из базы на карту ---
    # Кнопка «Мир» есть ТОЛЬКО в базе: на карте мира на её месте кнопка дома.
    # Поэтому она же и якорь экрана базы — отдельный шаблон вида не нужен.
    # Замер по reference/29_base_view.png: база 1.00, все прочие 28 кадров
    # <= 0.27, так что порог 0.7 стоит с большим запасом.
    world_button_region: tuple = (840, 1700, 240, 220)   # правый нижний угол
    world_button_threshold: float = 0.7
    world_button_xy: tuple = (975, 1830)   # фолбэк, если шаблон не нашёлся
    world_button_attempts: int = 2         # больше — считаем аномалией

    # --- Виджет «Отряд N/4» (левый верх) ---
    # Виджет смещается по вертикали между кадрами -> якорь-слово «Отряд» ищем
    # в полосе, счётчик читаем по фикс. смещению от найденного матча.
    squad_total: int = 4
    # Занимать ли 4-й отряд. Снято по умолчанию: один отряд остаётся человеку.
    # Переключается чекбоксом в GUI прямо на ходу — движок читает cfg каждую
    # итерацию.
    use_fourth_squad: bool = False
    squad_header_band: tuple = (0, 200, 470, 220)   # (x, y, w, h) полоса поиска якоря
    squad_header_threshold: float = 0.7             # чисто: есть 0.96-1.00, нет 0.14-0.15
    squad_count_offset: tuple = (232, -2, 22, 42)   # (dx, dy, w, h) региона цифры N от матча

    # --- Антибот: человечные тапы ---
    tap_size_default: tuple = (40, 24)   # ±20 / ±12 от центра для координат без размера

    # --- Антибот: размеры кнопок для ФИКСИРОВАННЫХ координат ---
    # У шаблонных кнопок размер приходит из шаблона (см. vision.find_button),
    # здесь только те, что тапаются по координате из конфига. Замерено по
    # reference/*.png; заниженное значение безопаснее завышенного — сэмплим
    # всё равно только центральные tap_inset долей бокса.
    tap_sizes: dict = field(default_factory=lambda: {
        "corruption_search_icon": (86, 86),
        "corruption_tab": (200, 64),
        "corruption_search": (300, 88),
        "corruption_assault": (280, 84),
        "corruption_boost_energy": (300, 88),
        "flask_use": (150, 56),
        "energy_window_close": (60, 60),
        "energy_open": (60, 60),
        "exit_cancel": (200, 72),
        "preview_close": (400, 160),
        "squad_slot": (180, 120),
        "event_button": (120, 120),
        "search_thief_tab": (200, 64),
        "search_button": (240, 84),
        "world_button": (140, 140),      # кнопка ~174x170, берём с запасом внутрь
        # Тап по ЦЕЛИ на карте — не кнопка, а иконка черепа с мелким хитбоксом.
        # Промах зумит карту, детекция перестаёт ловить спрайты, а отзумить бот
        # сам не может. Координата выстрадана калибровкой (центр bbox = лицо
        # черепа, offset не нужен) -> разброс минимальный, по эффекту не шире
        # нынешнего jitter ±4px. Человечность тут даёт время, а не координата.
        "target": (16, 16),
    })

    # --- Антибот: человечные паузы ---
    human_enabled: bool = True
    tap_inset: float = 0.5             # доля бокса, внутри которой сэмплим точку
    human_tap_hold: bool = False       # переменная длительность нажатия (input swipe)
    tap_hold_ms: tuple = (40, 110)
    delay_react: tuple = (0.25, 1.8)   # «увидел экран -> нажал», логнормаль
    delay_settle_mult: tuple = (1.0, 1.35)   # множитель к откалиброванной паузе
    delay_poll: tuple = (0.3, 0.5)     # интервал опроса в _wait_*
    delay_idle_mult: tuple = (1.0, 1.4)      # множитель к паузе «все отряды заняты»

    def squad_limit(self):
        """Сколько отрядов бот имеет право занять одновременно."""
        return self.squad_total if self.use_fourth_squad else self.squad_total - 1

    def tap_box(self, name, xy):
        """Бокс для тапа по ФИКСИРОВАННОЙ координате: размер берём по имени
        кнопки из tap_sizes, для неизвестных имён — tap_size_default."""
        w, h = self.tap_sizes.get(name, self.tap_size_default)
        return Box(int(xy[0]), int(xy[1]), int(w), int(h))
