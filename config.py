    corruption_assault_xy: tuple = (540, 1245)      # «Штурм» на панели босса (фолбэк к шаблону)
    corruption_energy_cost: int = 20                # стоимость штурма
    # Гейт «Легкая победа». Выключен: уровень скверны фиксирует человек, значит
    # босс заведомо проходим. Включать, если поднять уровень.
    corruption_verdict_gate: bool = False
    corruption_poll_interval_s: float = 10.0        # опрос, когда все отряды заняты
    # «Назад» на чистой карте открывает «Выйти из игры?» — жмём «Отмена»
    # (фолбэк к шаблону exit_cancel), иначе следующий тап подтвердит выход.
    exit_cancel_xy: tuple = (297, 1030)
    # Окно «Восстановить энергию» в этом режиме открывается кнопкой «Увеличить
    # энергию» на превью. Строк 3 или 4 (при четырёх третья — зелёная +10),
    # поэтому Y кнопки «Использовать» берём от найденной строки фиолетовой
    # склянки, а фиксирован только X.
    flask_use_x: int = 858
    energy_window_close_xy: tuple = (1000, 375)
