    # --- Пороги стратегии ---
    flask_stop_threshold: int = 180      # склянок < 180 -> STOP
    energy_refill_threshold: int = 20    # энергия < 20 -> REFILL
    farm_levels: frozenset = frozenset({5})
    boss_level_threshold: int = 50       # эвристика: level >= -> кандидат в боссы
